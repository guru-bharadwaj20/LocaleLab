import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import type { Capture, Profile, RunResult } from "../types.js";

export const SPEC_FILE = "localelab.generated.spec.ts";

function literal(value: unknown): string {
  return JSON.stringify(value);
}

function identifier(profile: Profile): string {
  return profile.id.replace(/[^A-Za-z0-9]+/g, "_");
}

/**
 * One describe block per profile. Each block re-creates the browser context the
 * capture used and re-checks the deterministic facts LocaleLab observed, so the
 * spec passes against the page as it was and fails when a regression appears.
 */
function renderProfileBlock(capture: Capture, result: RunResult): string {
  const { profile, evidence } = capture;
  const marked = evidence.markedValues.filter((v) => !v.ignored && v.expected !== null && !v.error);
  const markerChecks = marked
    .map(
      (v) => `
    // ${v.kind} marker ${literal(v.marker)} on ${v.path}
    await expect(page.locator(${literal(`[data-localelab-${v.kind}=${JSON.stringify(v.marker)}]`)}).first()).toHaveText(
      new RegExp(${literal(escapeForRegex(v.expected ?? ""))}),
    );`,
    )
    .join("");

  const langCheck =
    evidence.documentLang === null
      ? `    // The page declared no <html lang>; add one and tighten this check.`
      : `    await expect(page.locator("html")).toHaveAttribute("lang", /^${escapeForRegex(profile.language)}(?:[-_]|$)/i);`;

  const dirCheck =
    profile.direction === "rtl"
      ? `    expect(await page.evaluate(() => getComputedStyle(document.documentElement).direction)).toBe("rtl");`
      : `    expect(await page.evaluate(() => getComputedStyle(document.documentElement).direction)).toBe("ltr");`;

  return `
test.describe(${literal(`${profile.label} (${profile.locale})`)}, () => {
  test.use({
    locale: ${literal(profile.locale)},
    timezoneId: ${literal(profile.timezone)},
    viewport: ${literal(result.viewport)},
    colorScheme: ${literal(profile.colorScheme ?? "light")},
  });

  test(${literal(`renders without locale regressions [${profile.id}]`)}, async ({ page }, testInfo) => {
    await page.goto(URL, { waitUntil: "load" });
    await page.waitForLoadState("networkidle").catch(() => undefined);

    // Browser emulation is in effect.
    expect(await page.evaluate(() => navigator.language)).toBe(${literal(profile.locale)});
    expect(await page.evaluate(() => Intl.DateTimeFormat().resolvedOptions().timeZone)).toBe(${literal(profile.timezone)});

    // No horizontal page overflow.
    const widths = await page.evaluate(() => ({
      scroll: Math.max(document.documentElement.scrollWidth, document.body ? document.body.scrollWidth : 0),
      client: document.documentElement.clientWidth,
    }));
    expect(widths.scroll, "page should not be wider than the viewport").toBeLessThanOrEqual(widths.client + 1);

    // Document metadata.
${langCheck}
${dirCheck}
${markerChecks}

    await page.screenshot({ path: testInfo.outputPath(${literal(`${identifier(profile)}.png`)}), fullPage: true });
  });
});`;
}

function escapeForRegex(value: string): string {
  // Collapse space variants so NBSP in Intl output still matches a plain-space render and vice versa.
  return value
    .replace(/[.*+?^${}()|[\]\\]/g, "\\$&")
    .replace(/[   ]/g, "[\\s\\u00a0\\u202f]")
    .replace(/[‎‏؜]/g, "");
}

export function renderPlaywrightSpec(result: RunResult): string {
  const blocks = result.captures
    .filter((c) => !c.error)
    .map((c) => renderProfileBlock(c, result))
    .join("\n");
  return `// Generated by LocaleLab ${result.version} on ${result.startedAt}.
// Source: ${result.url}
//
// Drop this file into a Playwright project (npm i -D @playwright/test) and run
// \`npx playwright test ${SPEC_FILE}\`. Edit freely: it is a starting point, not a contract.
import { test, expect } from "@playwright/test";

const URL = process.env.LOCALELAB_URL ?? ${literal(result.url)};
${blocks}
`;
}

export async function writePlaywrightSpec(result: RunResult, outDir: string): Promise<string> {
  await mkdir(outDir, { recursive: true });
  const file = path.join(outDir, SPEC_FILE);
  await writeFile(file, renderPlaywrightSpec(result), "utf8");
  return file;
}
